/// Шифрует данные с использованием алгоритма AES-256-GCM.
///
/// # Аргументы
/// * `key` - 32-байтовый ключ шифрования (256 бит)
/// * `plaintext` - исходные данные для шифрования
///
/// # Возвращаемое значение
/// Возвращает `Result<Vec<u8>>` с зашифрованными данными в следующем формате:
/// - Основная часть: зашифрованный текст (ciphertext)
/// - В конце: 12-байтовый одноразовый номер (nonce), использованный при шифровании
///
/// # Ошибки
/// Возвращает ошибку в случаях:
/// - Некорректная длина ключа (не 32 байта)
/// - Проблемы с криптографическими операциями
/// - Проблемы с генерацией случайных чисел
///
/// # Безопасность
/// - Используется криптографически безопасный генератор случайных чисел (OsRng)
/// - Для каждого шифрования генерируется уникальный nonce
/// - Режим GCM обеспечивает как конфиденциальность, так и аутентификацию данных
///
/// # Примечание
/// Для расшифровки используйте соответствующую функцию decrypt_aes256gcm,
/// которая ожидает данные в том же формате (ciphertext + nonce в конце)
pub fn encrypt_aes256gcm(key: &[u8], plaintext: &[u8]) -> error::Result<Vec<u8>> {
    let cipher = Aes256Gcm::new_from_slice(key)?;
    let nonce = Aes256Gcm::generate_nonce(&mut OsRng);
    let mut ciphertext = cipher.encrypt(&nonce, plaintext)?;
    ciphertext.extend_from_slice(&nonce);
    Ok(ciphertext)
}

/// Дешифрует данные, зашифрованные алгоритмом AES-256-GCM.
///
/// # Аргументы
/// * `key` - 32-байтовый ключ шифрования (256 бит), должен совпадать с ключом,
///   использованным при шифровании
/// * `ciphertext` - зашифрованные данные в формате, возвращаемом функцией `encrypt_aes256gcm`:
///   - Основная часть: зашифрованный текст
///   - Последние 12 байтов: одноразовый номер (nonce), использованный при шифровании
///
/// # Возвращаемое значение
/// Возвращает `Result<Vec<u8>>` с расшифрованными исходными данными
///
/// # Ошибки
/// Возвращает ошибку в случаях:
/// - Слишком короткие зашифрованные данные (менее 12 байт)
/// - Некорректная длина ключа (не 32 байта)
/// - Неверный ключ шифрования
/// - Поврежденные или неаутентичные данные
/// - Проблемы с криптографическими операциями
///
/// # Безопасность
/// - Функция проверяет аутентичность данных перед дешифрованием
/// - В случае неаутентичных данных возвращается ошибка, предотвращая
///   обработку потенциально поддельной информации
pub fn decrypt_aes256gcm(key: &[u8], ciphertext: &[u8]) -> error::Result<Vec<u8>> {
    if ciphertext.len() < 12 {
        return Err(error::Error::ShortCiphertext);
    }
    let (ciphertext, nonce_bytes) = ciphertext.split_at(ciphertext.len() - 12);
    let cipher = Aes256Gcm::new_from_slice(key)?;
    let nonce = Nonce::from_slice(nonce_bytes);
    let plaintext = cipher.decrypt(nonce, ciphertext)?;

    Ok(plaintext)
}

/// Производит ключ из мастер-пароля с использованием алгоритма Argon2.
///
/// # Аргументы
/// * `master_password` - мастер-пароль в виде защищенной строки (`SecretString`).
///   Автоматически очищается из памяти после использования.
/// * `salt` - соль для усиления безопасности ключевой деривации. Должна быть
///   уникальной для каждого пользователя/приложения. Рекомендуемая длина - 16 байт.
///
/// # Возвращаемое значение
/// Возвращает `Result<[u8; 32]>` с 32-байтовым ключом (256 бит), пригодным для
/// использования в AES-256 шифровании.
///
/// # Ошибки
/// Возвращает ошибку в случаях:
/// - Проблемы с алгоритмом хеширования Argon2
/// - Некорректные параметры для ключевой деривации
///
/// # Безопасность
/// - Использует алгоритм Argon2 - победитель конкурса парольных хешей
/// - Автоматически очищает мастер-пароль из памяти после использования
/// - Устойчив к атакам перебором (brute-force) и радужным таблицам (rainbow tables)
/// - Требует использования уникальной соли для каждого пользователя
///
/// # Рекомендации
/// - Используйте случайную соль длиной не менее 16 байт
/// - Храните соль вместе с зашифрованными данными (в открытом виде)
/// - Никогда не используйте одну и ту же соль для разных пользователей
/// - Мастер-пароль должен быть достаточно сложным
///
/// # Примечание
/// Функция предназначена для преобразования человеко-читаемого пароля в
/// криптографически стойкий ключ фиксированной длины.
pub fn derive_key(master_password: SecretString, salt: &[u8]) -> error::Result<[u8; 32]> {
    let argon2 = Argon2::default();

    let mut key = [0u8; 32];
    argon2
        .hash_password_into(master_password.expose_secret().as_bytes(), salt, &mut key)
        .map_err(error::Error::Argon2)?;

    Ok(key)
}

/// Генерирует случайный пароль заданной длины.
///
/// # Аргументы
///
/// * `length` - длина генерируемого пароля (количество символов)
///
/// # Возвращаемое значение
///
/// Возвращает строку (`String`) содержащую случайно сгенерированный пароль.
///
/// # Состав символов
///
/// Пароль включает символы из четырех категорий:
/// - Заглавные буквы: A-Z
/// - Строчные буквы: a-z
/// - Цифры: 0-9
/// - Специальные символы: !@#$%^&*()_-+=[]{}|;:,.<>?
/// # Безопасность
///
/// - Использует криптографически безопасный генератор случайных чисел
/// - Равномерное распределение символов из всех категорий
/// - Подходит для генерации паролей различной сложности
///
/// # Рекомендации
///
/// - Для обычных аккаунтов рекомендуется длина 12-16 символов
/// - Для важных аккаунтов используйте 20+ символов
/// - Пароль содержит символы из всех четырех категорий для повышения энтропии
///
/// # Ограничения
///
/// - Функция может паниковать при пустом наборе символов (маловероятно)
/// - Длина пароля ограничена только возможностями памяти
/// - Не гарантирует обязательное наличие символов из каждой категории в коротких паролях
pub fn generate_password(length: usize) -> String {
    let charset = "ABCDEFGHIJKLMNOPQRSTUVWXYZ\
                      abcdefghijklmnopqrstuvwxyz\
                      0123456789\
                      !@#$%^&*()_-+=[]{}|;:,.<>?";

    let password: String = (0..length)
        .map(|_| {
            let idx = rand::random_range(0..charset.len());
            charset.chars().nth(idx).unwrap()
        })
        .collect();

    password
}

#[cfg(test)]
mod crypto_tests {
    use super::*;

    #[test]
    fn derive_test() {
        let master_password = SecretString::new("master_pass".into());
        let salt = b"unique_user_salt";
        let result = derive_key(master_password, salt);
        assert!(result.is_ok());
        println!("Derive result:");
        println!("{:?}", result.unwrap());
    }

    #[test]
    fn en_dec_crypt_test() -> error::Result<()> {
        const TEST_KEY: &[u8] = b"32_byte_secret_key_for_aes256gcm";

        let plaintext = b"Secret password data";
        println!("Original: {:?}", String::from_utf8_lossy(plaintext));

        let enc_data = encrypt_aes256gcm(TEST_KEY, plaintext)?;
        println!("Encrypted: {:?}", enc_data);

        let decrypted = decrypt_aes256gcm(TEST_KEY, &enc_data)?;
        println!("Decrypted: {:?}", String::from_utf8_lossy(&decrypted));

        assert_eq!(plaintext, decrypted.as_slice());

        Ok(())
    }

    #[test]
    fn generate_password_test() {
        let password = generate_password(32);
        assert_eq!(password.len(), 32);
        dbg!(&password);

        let password = generate_password(16);
        assert_eq!(password.len(), 16);
        dbg!(&password);
    }
}
